-- Owns ONE table: users. Everything else (claims, assessments, ...) lives in the other services' own databases.
-- Other services refer to a user only by id (the JWT "sub" claim), never by foreign key: the databases are separate.
--
-- Conventions used by all three services' schemas
--   * Primary keys are BIGINT identity columns.
--   * Audit columns: created_at on every table; updated_at on every table whose rows can change.
--   * Timestamps are TIMESTAMP WITH TIME ZONE (the services store UTC instants).
--   * Enumerations are stored as VARCHAR and guarded by CHECK constraints that mirror the Java enums.
--   * Hibernate only VALIDATES this schema (spring.jpa.hibernate.ddl-auto=validate); Flyway is the sole owner of DDL.
-- =====================================================================================================================


-- ---------------------------------------------------------------------------------------------------------------------
-- users : every person who can log in (CLAIMANT, CLAIMS_STAFF, MANAGER)
-- ---------------------------------------------------------------------------------------------------------------------
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(100)             NOT NULL,
    email         VARCHAR(254)             NOT NULL,                 -- login name; always stored trimmed + lower-case
    password_hash VARCHAR(100)             NOT NULL,                 -- BCrypt hash, never the password
    role          VARCHAR(20)              NOT NULL,                 -- CLAIMANT | CLAIMS_STAFF | MANAGER
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,                 -- audit: when the account was created
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,                 -- audit: when the account was last changed

    CONSTRAINT uq_users_email           UNIQUE (email),
    CONSTRAINT ck_users_email_lowercase CHECK (email = LOWER(email)),   -- the app normalises; the database insists
    CONSTRAINT ck_users_role            CHECK (role IN ('CLAIMANT', 'CLAIMS_STAFF', 'MANAGER'))
);

-- Staff lists ("all claims staff") filter on role.
CREATE INDEX idx_users_role ON users (role);
