-- =====================================================================================================================
-- CHUBB APAC CLAIMS PLATFORM  |  ASSESSMENT SERVICE  |  V1__schema.sql
-- ---------------------------------------------------------------------------------------------------------------------
-- Owns two tables. The claim itself, its status and its amount live in claim-service's database; this service never
-- copies the claim's live status, so what it shows cannot go stale.
--     claim_assessments   one row per claim a claims staff member has taken on: who took it, and their decision
--     claim_notes         the claims staff's internal review trail (never shown to claimants)
--
-- Cross-service references are LOGICAL, not foreign keys, because every service has its own database:
--     claim_assessments.claim_id    -> claim-service claims.id
--     claim_assessments.staff_id  -> auth-service users.id (a CLAIMS_STAFF)
--     claim_notes.claim_id          -> claim-service claims.id   (a note may exist before the claim is assigned,
--                                       so it deliberately has no foreign key to claim_assessments either)
-- =====================================================================================================================


-- ---------------------------------------------------------------------------------------------------------------------
-- claim_assessments
-- ---------------------------------------------------------------------------------------------------------------------
CREATE TABLE claim_assessments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id        BIGINT                   NOT NULL,               -- logical ref -> claim-service claims.id
    claim_number    VARCHAR(30)              NOT NULL,               -- convenience copy for display, e.g. CLM-2026-000042
    staff_id      BIGINT                   NOT NULL,               -- logical ref -> auth-service users.id
    staff_name    VARCHAR(100),                                    -- snapshot from the staff member's token
    decision        VARCHAR(20),                                     -- NULL while the claim is still being reviewed
    decision_reason VARCHAR(2000),                                   -- the staff member's comment / reason
    assigned_at     TIMESTAMP WITH TIME ZONE NOT NULL,               -- when the staff member took the claim
    decided_at      TIMESTAMP WITH TIME ZONE,                        -- when they approved or rejected it
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,               -- audit: row created
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,               -- audit: row last changed
    version         BIGINT                   NOT NULL DEFAULT 0,     -- optimistic lock

    CONSTRAINT uq_claim_assessments_claim_id UNIQUE (claim_id),      -- one assessment per claim
    CONSTRAINT ck_claim_assessments_decision CHECK (decision IS NULL OR decision IN ('APPROVED', 'REJECTED')),
    CONSTRAINT ck_claim_assessments_decided  CHECK ((decision IS NULL) = (decided_at IS NULL)),  -- decision <=> timestamp
    CONSTRAINT ck_claim_assessments_updated_after_created CHECK (updated_at >= created_at)
);

CREATE INDEX idx_claim_assessments_staff_id ON claim_assessments (staff_id);   -- staff workload, names


-- ---------------------------------------------------------------------------------------------------------------------
-- claim_notes : insert-only (created_at is the audit timestamp; staff_id says who wrote it)
-- ---------------------------------------------------------------------------------------------------------------------
CREATE TABLE claim_notes (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id     BIGINT                   NOT NULL,                  -- logical ref -> claim-service claims.id
    staff_id   BIGINT                   NOT NULL,                  -- logical ref -> auth-service users.id
    staff_name VARCHAR(100),
    note_type    VARCHAR(20)              NOT NULL,                  -- GENERAL | INFO_REQUEST | APPROVAL | REJECTION
    content      VARCHAR(2000)            NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,                  -- audit: when it was written

    CONSTRAINT ck_claim_notes_note_type CHECK (note_type IN ('GENERAL', 'INFO_REQUEST', 'APPROVAL', 'REJECTION'))
);

CREATE INDEX idx_claim_notes_claim_id ON claim_notes (claim_id, created_at);       -- a claim's review trail
CREATE INDEX idx_claim_notes_staff_id ON claim_notes (staff_id);
